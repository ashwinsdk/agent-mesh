    def sync(self):
        out = [f"AGENTS.md: {upsert_block(self.p.root / 'AGENTS.md', CORE)}"]
        p = self.p.root / ".agents" / "hooks.json"
        cur = json.loads(p.read_text()) if p.exists() else {}
        def h(ev):
            return {"type": "command", "command": walk_up_cmd("antigravity", ev), "timeout": 5}
